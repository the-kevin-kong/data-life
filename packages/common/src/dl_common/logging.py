"""Structured logging setup.

`LOG_JSON=true` emits JSON lines (what you want in Cloud Run / Cloud Logging);
otherwise a colorized console renderer is used for local dev.
"""

from __future__ import annotations

import logging
import sys
from typing import Any, cast

import structlog

from dl_common.config import get_settings

_configured = False


def configure_logging() -> None:
    """Configure structlog + stdlib logging once, idempotently."""
    global _configured
    if _configured:
        return

    settings = get_settings()
    level = getattr(logging, settings.log_level.upper(), logging.INFO)

    logging.basicConfig(format="%(message)s", stream=sys.stdout, level=level)

    processors: list[Any] = [
        structlog.contextvars.merge_contextvars,
        structlog.processors.add_log_level,
        structlog.processors.TimeStamper(fmt="iso"),
        structlog.processors.StackInfoRenderer(),
        structlog.processors.format_exc_info,
    ]
    processors.append(
        structlog.processors.JSONRenderer()
        if settings.log_json
        else structlog.dev.ConsoleRenderer()
    )

    structlog.configure(
        processors=processors,
        wrapper_class=structlog.make_filtering_bound_logger(level),
        logger_factory=structlog.PrintLoggerFactory(),
        cache_logger_on_first_use=True,
    )
    _configured = True


def get_logger(name: str | None = None) -> structlog.stdlib.BoundLogger:
    """Return a bound structlog logger, configuring logging on first use."""
    configure_logging()
    return cast(structlog.stdlib.BoundLogger, structlog.get_logger(name))
